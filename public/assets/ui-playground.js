/* Krewire UI live preview playground — zero dependencies, no network.
 *
 * Two roles, both inert unless their markup is present:
 *
 * 1. Frame: inside a preview page (pages/ui/preview/<slug>.kiw, layout
 *    Preview) it forces the theme requested by ?theme=light|dark without
 *    touching the visitor's stored preference, shows the variant named in the
 *    URL hash (#variant=primary&size=md), and makes kui Tabs clickable.
 *
 * 2. Host: every element with [data-component-preview] (rendered by
 *    components/ComponentPreview.kiw or written by hand in a docs page) gets a
 *    light and a dark iframe of the matching preview page, toggle groups built
 *    from the variants that page actually contains, and copy buttons for the
 *    component source (/ui/source/<Name>.kiw.txt) and the usage snippet.
 *
 * The preview pages are generated by scripts/gen-ui-previews.py; every
 * variant is a real kui component rendered by `kiw build`.
 */
(function () {
  'use strict';

  var root = document.documentElement;

  // ---------------------------------------------------------------- frame --
  var forcedTheme = new URLSearchParams(window.location.search).get('theme');

  function applyForcedTheme() {
    if (forcedTheme !== 'light' && forcedTheme !== 'dark') return;
    if (!document.querySelector('.pv-main') && document.readyState !== 'loading') return;
    root.dataset.theme = forcedTheme;
    root.classList.toggle('dark', forcedTheme === 'dark');
    root.style.colorScheme = forcedTheme;
  }

  function selectFromHash() {
    var wanted = new URLSearchParams(window.location.hash.replace(/^#/, ''));
    var blocks = Array.prototype.slice.call(document.querySelectorAll('[data-pv]'));
    var match = blocks.filter(function (el) {
      var ok = true;
      wanted.forEach(function (value, key) {
        if (el.getAttribute('data-' + key) !== value) ok = false;
      });
      return ok;
    })[0] || document.querySelector('[data-pv][data-default]') || blocks[0];
    blocks.forEach(function (el) { el.classList.toggle('is-active', el === match); });
  }

  function initFrame() {
    applyForcedTheme();
    selectFromHash();
    root.classList.add('pv-ready');
    window.addEventListener('load', applyForcedTheme);
    window.addEventListener('hashchange', selectFromHash);
    document.addEventListener('click', function (e) {
      var tab = e.target && e.target.closest ? e.target.closest('.kiw-tab') : null;
      var list = tab && tab.closest('.kiw-tabs-list');
      if (!list) return;
      list.querySelectorAll('.kiw-tab').forEach(function (t) {
        var on = t === tab;
        t.classList.toggle('is-active', on);
        t.setAttribute('aria-selected', on ? 'true' : 'false');
      });
    });
  }

  // ----------------------------------------------------------------- host --
  var STRINGS = {
    en: {
      light: 'Light', dark: 'Dark', copySource: 'Copy .kiw Component', copyUsage: 'Copy Usage Example',
      copied: 'Copied!', failed: 'Copy failed', usage: 'Usage', open: 'Open in playground',
      loading: 'Loading preview…'
    },
    id: {
      light: 'Terang', dark: 'Gelap', copySource: 'Salin Komponen .kiw', copyUsage: 'Salin Contoh Penggunaan',
      copied: 'Tersalin!', failed: 'Gagal menyalin', usage: 'Penggunaan', open: 'Buka di playground',
      loading: 'Memuat pratinjau…'
    }
  };

  function strings() {
    // Docs pages carry their locale in <html lang>; site pages switch
    // language client-side and remember it in localStorage.
    var lang = (root.getAttribute('lang') || 'en').slice(0, 2);
    if (!/^\/(id\/)?docs(\/|$)/.test(window.location.pathname)) {
      try {
        var stored = localStorage.getItem('krewire-lang');
        if (stored && STRINGS[stored]) lang = stored;
      } catch (e) {}
    }
    return STRINGS[lang] || STRINGS.en;
  }

  function el(tag, attrs, text) {
    var node = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (k) { node.setAttribute(k, attrs[k]); });
    if (text != null) node.textContent = text;
    return node;
  }

  function copyText(text, done) {
    function fallback() {
      var ta = el('textarea', { readonly: '', style: 'position:fixed;top:-1000px;opacity:0' });
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      var ok = false;
      try { ok = document.execCommand('copy'); } catch (e) {}
      document.body.removeChild(ta);
      done(ok);
    }
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard.writeText(text).then(function () { done(true); }, fallback);
    } else {
      fallback();
    }
  }

  function flash(btn, label, ok, t) {
    btn.textContent = ok ? '✓ ' + t.copied : t.failed;
    btn.classList.toggle('is-copied', ok);
    setTimeout(function () { btn.textContent = label; btn.classList.remove('is-copied'); }, 1800);
  }

  function hydrate(host) {
    if (host.getAttribute('data-cpv-ready')) return;
    host.setAttribute('data-cpv-ready', '1');
    var t = strings();
    var name = host.getAttribute('data-component-preview');
    var slug = host.getAttribute('data-slug') || name.toLowerCase();
    var base = (host.getAttribute('data-base') || '/').replace(/\/?$/, '/');
    var state = {};
    var axes = [];
    var source = null;

    host.classList.add('cpv');
    host.textContent = '';

    var controls = el('div', { class: 'cpv-controls', 'aria-label': name + ' variants' });
    var stages = el('div', { class: 'cpv-stages' });
    var frames = ['light', 'dark'].map(function (theme) {
      var fig = el('figure', { class: 'cpv-stage cpv-stage-' + theme });
      fig.appendChild(el('figcaption', { class: 'cpv-stage-label' }, theme === 'light' ? t.light : t.dark));
      var frame = el('iframe', {
        class: 'cpv-frame',
        src: base + 'ui/preview/' + slug + '?theme=' + theme,
        title: name + ' — ' + (theme === 'light' ? t.light : t.dark),
        loading: 'lazy'
      });
      fig.appendChild(frame);
      stages.appendChild(fig);
      return frame;
    });

    var actions = el('div', { class: 'cpv-actions' });
    var copySrc = el('button', { type: 'button', class: 'cpv-btn' }, t.copySource);
    var copyUse = el('button', { type: 'button', class: 'cpv-btn cpv-btn-primary' }, t.copyUsage);
    actions.appendChild(copySrc);
    actions.appendChild(copyUse);
    if (!document.querySelector('.cpv-page')) {
      actions.appendChild(el('a', { class: 'cpv-link', href: base + 'ui/playground#' + slug }, t.open + ' →'));
    }

    var codeWrap = el('div', { class: 'cpv-code' });
    codeWrap.appendChild(el('span', { class: 'cpv-code-label' }, t.usage));
    var pre = el('pre');
    var code = el('code', {}, t.loading);
    pre.appendChild(code);
    codeWrap.appendChild(pre);

    host.appendChild(controls);
    host.appendChild(stages);
    host.appendChild(actions);
    host.appendChild(codeWrap);

    function docOf(frame) {
      try { return frame.contentDocument; } catch (e) { return null; }
    }

    function matches(block) {
      return axes.every(function (a) { return block.getAttribute('data-' + a) === state[a]; });
    }

    function render() {
      frames.forEach(function (frame) {
        var doc = docOf(frame);
        if (!doc) return;
        var active = null;
        doc.querySelectorAll('[data-pv]').forEach(function (b) {
          var on = matches(b);
          b.classList.toggle('is-active', on);
          if (on) active = b;
        });
        if (frame === frames[0] && active) {
          var usage = active.querySelector('.pv-usage');
          code.textContent = usage ? usage.textContent : '';
        }
        resize(frame);
      });
      controls.querySelectorAll('button[data-axis]').forEach(function (b) {
        var on = state[b.getAttribute('data-axis')] === b.getAttribute('data-value');
        b.setAttribute('aria-pressed', on ? 'true' : 'false');
      });
    }

    function resize(frame) {
      var doc = docOf(frame);
      if (!doc || !doc.body) return;
      var h = Math.max(doc.documentElement.scrollHeight, doc.body.scrollHeight);
      frame.style.height = Math.max(h, 120) + 'px';
    }

    function buildControls(doc) {
      var grid = doc.querySelector('[data-pv-axes]');
      axes = grid ? grid.getAttribute('data-pv-axes').split(',').filter(Boolean) : [];
      var def = doc.querySelector('[data-pv][data-default]') || doc.querySelector('[data-pv]');
      axes.forEach(function (axis) {
        var values = [];
        doc.querySelectorAll('[data-pv]').forEach(function (b) {
          var v = b.getAttribute('data-' + axis);
          if (v && values.indexOf(v) < 0) values.push(v);
        });
        state[axis] = def ? def.getAttribute('data-' + axis) : values[0];
        if (values.length < 2) return;
        var group = el('div', { class: 'cpv-group', role: 'group', 'aria-label': axis });
        group.appendChild(el('span', { class: 'cpv-group-label' }, axis));
        values.forEach(function (v) {
          var b = el('button', { type: 'button', class: 'cpv-toggle', 'data-axis': axis, 'data-value': v, 'aria-pressed': 'false' }, v);
          b.addEventListener('click', function () { state[axis] = v; render(); });
          group.appendChild(b);
        });
        controls.appendChild(group);
      });
    }

    var loaded = 0;
    frames.forEach(function (frame) {
      frame.addEventListener('load', function () {
        loaded += 1;
        var doc = docOf(frame);
        if (doc && !axes.length && !controls.childNodes.length) buildControls(doc);
        render();
        // Re-measure once web fonts and late layout settle.
        setTimeout(function () { resize(frame); }, 250);
        if (loaded === frames.length) host.classList.add('is-loaded');
      });
    });

    var srcURL = base + 'ui/source/' + name + '.kiw.txt';
    function loadSource() {
      if (source !== null) return Promise.resolve(source);
      return fetch(srcURL).then(function (r) {
        if (!r.ok) throw new Error(String(r.status));
        return r.text();
      }).then(function (text) { source = text; return text; });
    }
    if (window.fetch) loadSource().catch(function () {});

    copyUse.addEventListener('click', function () {
      copyText(code.textContent, function (ok) { flash(copyUse, t.copyUsage, ok, t); });
    });
    copySrc.addEventListener('click', function () {
      if (source !== null) {
        copyText(source, function (ok) { flash(copySrc, t.copySource, ok, t); });
        return;
      }
      loadSource().then(function (text) {
        copyText(text, function (ok) { flash(copySrc, t.copySource, ok, t); });
      }, function () { flash(copySrc, t.copySource, false, t); });
    });
  }

  function initHosts() {
    document.querySelectorAll('[data-component-preview]').forEach(hydrate);
  }

  // ----------------------------------------------------------------- boot --
  applyForcedTheme();
  function boot() {
    if (document.querySelector('.pv-main')) {
      initFrame();
    } else {
      initHosts();
    }
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})();
